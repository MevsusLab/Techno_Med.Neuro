class PhraseGraph:
    def __init__(self):
        self.adjacency = {}
        for word, edges in _EDGES.items():
            if word not in _ALL_WORDS:
                raise ValueError('Unknown phrase source: ' + word)
            for target, weight in edges:
                if target not in _ALL_WORDS or target == word or not .5 <= weight <= 1:
                    raise ValueError('Invalid phrase transition: ' + word + ' -> ' + target)
            self.adjacency[word] = tuple(sorted(edges, key=lambda edge: edge[1], reverse=True))
        if set(self.adjacency) != set(_ALL_WORDS):
            raise ValueError('Phrase vocabulary is incomplete')

    def predict(self, word, n=4):
        if not isinstance(n, int) or n < 0:
            raise ValueError('Prediction count must be a nonnegative integer')
        if n == 0:
            return []
        # Graph topology is static: sort once, then use a tiny adjacency lookup.
        candidates = []
        for target in [edge[0] for edge in self.adjacency.get(word, ())] + ROOT_WORDS:
            if target != word and target in self.adjacency and target not in candidates:
                candidates.append(target)
                if len(candidates) == n:
                    break
        return candidates

    def all_words(self):
        return list(_ALL_WORDS)

    def has_word(self, word):
        return word in self.adjacency

    def edges_from(self, word):
        return list(self.adjacency.get(word, []))
